import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {pathToFileURL} from 'node:url';
import {createServer} from 'vite';

const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
export async function movementCli(args) {
  const [command, input, output, evidence] = args;
  if (!['synthetic', 'import', 'report'].includes(command) || !input || command !== 'synthetic' && !output)
    throw new Error('Usage: node tools/movement-conformance.mjs synthetic OUTPUT.json | import REFERENCE.json OUTPUT.json EVIDENCE_FILE | report REFERENCE.json OUTPUT.json');
  const vite = await createServer({server: {middlewareMode: true, hmr: false, ws: false}, appType: 'custom', logLevel: 'silent'});
  try {
    const {MOVEMENT_SCHEMA, MOVEMENT_MODEL, movementScenarios, runMovementScenario, parseMovementReference, compareMovementReference} =
      await vite.ssrLoadModule('/src/range/movement-conformance.ts');
    if (command === 'synthetic') {
      const source = 'src/range/actor-physics.ts';
      const reference = {schema: MOVEMENT_SCHEMA, modelVersion: MOVEMENT_MODEL,
        provenance: {kind: 'synthetic-regression', source, build: 'trainer-only; NOT CS2 measured trajectories',
          recordedAt: new Date().toISOString(), method: 'Generated by runMovementScenario from the shared motor; regression only.',
          sha256: hash(fs.readFileSync(source)), precision: 'Double-precision synthetic outputs, 1/128 s steps with command-edge splits.'},
        tolerances: {timeSeconds: 1e-8, positionUnits: 1e-7, speedUnitsPerSecond: 1e-7, heightUnits: 1e-7,
          stoppingDistanceUnits: 1e-7, landingDisplacementUnits: 1e-7, stopSpeedUnitsPerSecond: .1,
          rationale: 'Synthetic determinism tolerance only, not a manually captured CS2 acceptance budget. Set capture tolerances BEFORE comparison using observed precision.'},
        scenarios: movementScenarios.map(scenario => ({scenario, samples: runMovementScenario(scenario)}))};
      parseMovementReference(reference);
      fs.writeFileSync(input, JSON.stringify(reference, null, 2) + '\n');
      return {kind: reference.provenance.kind, scenarios: reference.scenarios.length, output: input};
    }
    if (fs.statSync(input).size > 16 * 1024 * 1024) throw new Error('Reference exceeds 16 MiB import limit');
    const bytes = fs.readFileSync(input), reference = parseMovementReference(JSON.parse(bytes));
    if (command === 'import') {
      if (!evidence || hash(fs.readFileSync(evidence)) !== reference.provenance.sha256) throw new Error('Evidence file must match declared provenance SHA-256');
      if (path.resolve(input) === path.resolve(output) || path.resolve(evidence) === path.resolve(output)) throw new Error('Import must not overwrite source evidence');
      fs.writeFileSync(output, JSON.stringify(reference, null, 2) + '\n');
      return {kind: reference.provenance.kind, referenceSha256: hash(bytes), output};
    }
    const report = {...compareMovementReference(reference), referenceSha256: hash(bytes)};
    if (path.resolve(input) === path.resolve(output)) throw new Error('Report must not overwrite reference');
    fs.writeFileSync(output, JSON.stringify(report, null, 2) + '\n');
    const plot = output.replace(/\.json$/i, '') + '.svg';
    fs.writeFileSync(plot, movementPlot(report));
    return {passed: report.passed, provenance: report.provenance.kind, scenarios: report.scenarios.map(({id, passed, failures, maxErrors}) => ({id, passed, failures, maxErrors})), output, plot};
  } finally {await vite.close();}
}

const escape = value => String(value).replace(/[<>&"]/g, c => ({'<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;'}[c]));
function movementPlot(report) {
  const width = 1000, rowHeight = 205, height = 65 + report.scenarios.length * rowHeight;
  const lines = [`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`,
    '<rect width="100%" height="100%" fill="white"/><g font-family="monospace" font-size="12" fill="#182329">',
    `<text x="20" y="22">Movement comparison: ${escape(report.provenance.kind)} (NOT a parity certificate)</text>`,
    '<text x="20" y="43">Reference: red; trainer: blue. Time (seconds) on X. Units: Source units and u/s.</text>'];
  report.scenarios.forEach((scenario, row) => {
    const top = 65 + row * rowHeight;
    lines.push(`<text x="20" y="${top + 12}">${escape(scenario.id)}: ${scenario.passed ? 'PASS' : escape(scenario.failures.join(', '))}</text>`);
    ['speed', 'feet', 'eye'].forEach((metric, col) => {
      const left = 45 + col * 325, y = top + 38, w = 280, h = 125;
      const values = scenario.curves.flatMap(c => [c.expected[metric], c.actual[metric]]);
      const min = Math.min(0, ...values), max = Math.max(min + 1, ...values), end = scenario.curves.at(-1).expected.time;
      lines.push(`<text x="${left}" y="${y - 5}">${metric} [${min.toFixed(1)}, ${max.toFixed(1)}]</text>`,
        `<path d="M${left},${y}v${h}h${w}" fill="none" stroke="#555"/>`);
      for (const [kind, color] of [['expected', '#c12d42'], ['actual', '#1679a1']]) {
        const points = scenario.curves.map(c => `${(left + c.expected.time / end * w).toFixed(2)},${(y + h - (c[kind][metric] - min) / (max - min) * h).toFixed(2)}`).join(' ');
        lines.push(`<polyline points="${points}" fill="none" stroke="${color}" stroke-width="1.4"${kind === 'actual' ? ' stroke-dasharray="4 2"' : ''}/>`);
      }
      lines.push(`<text x="${left}" y="${y + h + 16}">0</text><text x="${left + w - 30}" y="${y + h + 16}">${end.toFixed(2)} s</text>`);
    });
  });
  return lines.join('\n') + '</g></svg>\n';
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {const result = await movementCli(process.argv.slice(2)); console.log(JSON.stringify(result, null, 2)); if (result.passed === false) process.exitCode = 1;}
  catch (error) {console.error(error.message); process.exitCode = 1;}
}
